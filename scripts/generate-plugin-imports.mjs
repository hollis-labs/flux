#!/usr/bin/env node
// Generates Nanite's React loader registry from the module-owned libs/ui/ui-go/envelopes
// catalog. Generic manifest/schema parsing stays in libs/ui/ui-go/envelopes; this file
// owns only Nanite's component existence checks and host presentation policy.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { exportCatalog } from './lib/envelope-catalog.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT_FILE = join(ROOT, 'src', 'generated', 'plugin-envelopes.ts');
const UI_SRC = join(ROOT, 'src');
const CHECK_MODE = process.argv.includes('--check');

// These interactive cards need the complete wrapper so persisted responses
// hydrate after reload. This is a Nanite renderer policy, not schema metadata.
const CORE_OVERRIDES = {
  'approval-card': { props: 'envelope' },
  'proposal-card': { props: 'envelope' },
  'confirmation-card': { props: 'envelope' },
  'subagent-spawn-approval': { props: 'envelope' },
  'elicitation-prompt': { props: 'envelope' },
};

// The libs/ui/ui-go/envelopes manifest declares wire identity only; which
// component renders a type is host policy and lives here (it was manifest
// metadata through go-envelopes v0.4.x). `null` = backend-only, no component.
const E = 'components/chat/envelopes';
const HOST_COMPONENTS = {
  'approval-card': [`${E}/ApprovalCard`, 'ApprovalCard'],
  'artifact-mini': [`${E}/ArtifactMiniCard`, 'ArtifactMiniCard'],
  'chat-loop-terminated': [`${E}/ChatLoopTerminatedCard`, 'ChatLoopTerminatedCard'],
  'confirmation-card': [`${E}/primitives/ConfirmationCard`, 'ConfirmationCard'],
  'diff-card': [`${E}/primitives/DiffCard`, 'DiffCard'],
  'document-viewer': [`${E}/DocumentViewerCard`, 'DocumentViewerCard'],
  'elicitation-prompt': [`${E}/ElicitationPromptCard`, 'ElicitationPromptCard'],
  'error-report': [`${E}/ErrorCard`, 'ErrorCard'],
  'info-card': [`${E}/primitives/InfoCard`, 'InfoCard'],
  'list-card': [`${E}/primitives/ListCard`, 'ListCard'],
  'metric-card': [`${E}/primitives/MetricCard`, 'MetricCard'],
  'progress-card': [`${E}/primitives/ProgressCard`, 'ProgressCard'],
  'proposal-card': [`${E}/ProposalCard`, 'ProposalCard'],
  'report-card': [`${E}/ReportCard`, 'ReportCard'],
  'session-task': null,
  'subagent-spawn-approval': [`${E}/ApprovalCard`, 'ApprovalCard'],
  'table-card': [`${E}/primitives/TableCard`, 'TableCard'],
  'timeline-card': [`${E}/primitives/TimelineCard`, 'TimelineCard'],
};

const VALID_PROPS = new Set(['approval', 'proposal', 'envelope']);

function coreEntries(catalog) {
  return catalog.types.map((entry) => {
    if (entry.source !== 'core') {
      throw new Error(`build-time catalog unexpectedly contains non-core type ${entry.name}`);
    }
    if (!(entry.name in HOST_COMPONENTS)) {
      throw new Error(
        `envelope ${entry.name}: no host component mapping; add it to HOST_COMPONENTS (null if backend-only)`,
      );
    }
    const [component, exportName] = HOST_COMPONENTS[entry.name] ?? [];
    return {
      type: entry.name,
      component,
      export: exportName,
      props: CORE_OVERRIDES[entry.name]?.props,
    };
  });
}

function validateHostMetadata(entries) {
  for (const entry of entries) {
    if (Boolean(entry.component) !== Boolean(entry.export)) {
      throw new Error(`envelope ${entry.type}: component and export must be provided together`);
    }
    if (entry.props && !VALID_PROPS.has(entry.props)) {
      throw new Error(
        `envelope ${entry.type}: props ${JSON.stringify(entry.props)} must be one of ${[...VALID_PROPS].join(', ')}`,
      );
    }
    if (entry.component) {
      const componentPath = join(UI_SRC, `${entry.component}.tsx`);
      if (!existsSync(componentPath)) {
        throw new Error(`envelope ${entry.type}: component not found: ${componentPath}`);
      }
    }
  }
}

function generateLazyImport(entry) {
  const props = entry.props ? `\n    props: ${JSON.stringify(entry.props)},` : '';
  return `  ${JSON.stringify(entry.type)}: {
    component: lazy(() =>
      import(${JSON.stringify(`@/${entry.component}`)}).then((m) => ({
        default: m.${entry.export},
      })),
    ),
    source: "core",${props}
  },`;
}

export function generateOutput(entries, source) {
  const withComponents = entries.filter((entry) => entry.component && entry.export);
  const withoutComponents = entries.filter((entry) => !entry.component);
  const backendOnly = withoutComponents.length
    ? `\n  // Backend-only types (no frontend component): ${withoutComponents.map((entry) => entry.type).join(', ')}`
    : '';

  return `// AUTO-GENERATED by scripts/generate-plugin-imports.mjs — do not edit manually.
// Source: ${source.module}@${source.moduleVersion}; manifest ${source.manifestDigest}.
// Runtime plugin envelopes are registered dynamically via plugin-loader.ts.
// Run \`npm run generate:plugins\` to regenerate.
import { lazy } from "react";
import type { ComponentType } from "react";
import { getDynamicEnvelope } from "@/lib/plugin-loader";

// biome-ignore lint/suspicious/noExplicitAny: plugin envelope components have varied props
type LazyEnvelopeComponent = React.LazyExoticComponent<ComponentType<any>>;

export interface EnvelopeRegistryEntry {
  component: LazyEnvelopeComponent;
  source: string; // "core" | pluginId
  /** Prop-shape discriminator used by EnvelopeRenderer to build componentProps.
   * "approval" → { approval }, "proposal" → { proposal },
   * "envelope" → { envelope }, undefined → { data } (default). */
  props?: "approval" | "proposal" | "envelope";
}

// --- CORE ENVELOPES (generated from the released libs/ui/ui-go/envelopes catalog) ---
const CORE_ENTRIES: Record<string, EnvelopeRegistryEntry> = {${backendOnly}
${withComponents.map(generateLazyImport).join('\n')}
};

// Compiled-in registry — core only. Runtime plugins resolve via getDynamicEnvelope.
export const ENVELOPE_REGISTRY: Record<string, EnvelopeRegistryEntry> = {
  ...CORE_ENTRIES,
};

/**
 * Get the registry entry for a given envelope type, or undefined if unregistered.
 * Returns the full EnvelopeRegistryEntry so callers can inspect \`.component\` and
 * \`.props\` (prop-shape discriminator) without a separate lookup.
 * In recover mode, pass \`recoverMode: true\` to restrict to core-only entries.
 */
export function getEnvelopeComponent(
  type: string,
  recoverMode = false,
): EnvelopeRegistryEntry | undefined {
  const entry = ENVELOPE_REGISTRY[type];
  if (entry) {
    if (recoverMode && entry.source !== "core") return undefined;
    return entry;
  }

  if (recoverMode) return undefined;
  const dynamic = getDynamicEnvelope(type);
  if (!dynamic) return undefined;
  return { component: dynamic.component, source: dynamic.source };
}
`;
}

function main() {
  let catalog;
  try {
    catalog = exportCatalog(ROOT);
    const entries = coreEntries(catalog);
    validateHostMetadata(entries);
    const output = generateOutput(entries, catalog.source);

    if (CHECK_MODE) {
      if (!existsSync(OUTPUT_FILE) || readFileSync(OUTPUT_FILE, 'utf8') !== output) {
        console.error('CHECK FAILED: generated plugin envelope registry is stale.');
        console.error('Run: npm run generate:plugins');
        process.exit(1);
      }
      console.log('Plugin envelope registry is up to date.');
      return;
    }

    writeFileSync(OUTPUT_FILE, output, 'utf8');
    console.log(
      `Generated ${entries.length} core envelope registry entries from ${catalog.source.module}@${catalog.source.moduleVersion}`,
    );
  } catch (error) {
    console.error(`Envelope registry generation failed: ${error.message}`);
    process.exit(1);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
